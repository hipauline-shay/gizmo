import type {
  CombinedSummary,
  Evidence,
  Finding,
  GapAnalysis,
  NextStep,
  ProductAnalysis,
  UxState,
} from '../analysis/schemas'
import type { AnalysisMeta } from '../analysis/types'

export interface ExportArea {
  label: string
  analysis: ProductAnalysis
  meta?: AnalysisMeta
  specComparison?: GapAnalysis
}

export interface ExportReport {
  areas: ExportArea[]
  combined?: CombinedSummary
}

export function exportToMarkdown({ areas, combined }: ExportReport): string {
  const lines: string[] = []
  const [first] = areas
  if (!first) return '# Gizmo report\n\n_Nothing has been scanned yet._\n'

  const isSingleArea = areas.length === 1
  lines.push(`# ${isSingleArea ? first.analysis.featureName : `Gizmo report: ${areaNames(areas)}`}`)
  lines.push('')
  lines.push(`> Generated by Gizmo · ${areaCountLabel(areas)}`, '')

  const stakeholder = first.analysis.perspectives.stakeholder
  section(
    lines,
    'Summary',
    combined?.summary ?? (stakeholder.launchSummary || first.analysis.summary),
  )
  const launchGoal = combined?.launchGoal ?? stakeholder.launchGoal
  if (launchGoal) lines.push(`**Goal of this launch:** ${launchGoal}`, '')

  nextStepsSection(
    lines,
    '## Recommended next steps',
    combined?.nextSteps ?? first.analysis.nextSteps,
  )
  labeledFindingSection(
    lines,
    "## What's blocking release",
    areas.map((area) => ({
      label: area.label,
      findings: area.analysis.perspectives.stakeholder.launchBlockers,
    })),
    !isSingleArea,
  )

  for (const area of areas) areaSection(lines, area, isSingleArea)

  return tidy(lines)
}

export function exportTicketsToMarkdown({ areas }: ExportReport): string {
  const lines: string[] = []
  lines.push(
    `# ${areas.length === 1 && areas[0] ? areas[0].analysis.featureName : areaNames(areas)} — suggested tickets`,
  )
  lines.push('')
  lines.push(
    '> Generated by Gizmo. Each block below is ready to paste into Jira, Linear, or any tracker. Review before filing — "Likely" and "Unclear" findings should be verified first.',
  )
  lines.push('')

  let count = 0
  for (const area of areas) {
    const { analysis } = area
    const sources: TicketSource[] = [
      {
        category: 'Blocker',
        findings: analysis.perspectives.stakeholder.launchBlockers,
        titlePrefix: 'Fix launch blocker',
      },
      {
        category: 'Must fix',
        findings: analysis.perspectives.pm.mvpMustFix,
        titlePrefix: 'Fix before launch',
      },
      { category: 'Gap', findings: analysis.missingStates, titlePrefix: 'Add missing state' },
      { category: 'UX', findings: analysis.uxConcerns, titlePrefix: 'Fix UX concern' },
      { category: 'Decision', findings: analysis.risks, titlePrefix: 'Decide' },
      { category: 'Question', findings: analysis.openQuestions, titlePrefix: 'Clarify' },
    ]
    for (const source of sources)
      for (const finding of source.findings) {
        count += 1
        lines.push(...ticketBlock({ count, source, finding, area }))
      }

    for (const item of area.specComparison?.items ?? []) {
      if (item.status === 'built') continue
      count += 1
      lines.push(
        `## Ticket ${count}: ${gapTicketLabel(item.status)} — ${truncate(item.requirement, 80)}`,
      )
      lines.push('')
      lines.push(`**Type:** Spec gap (${gapStatusLabel(item.status)})`)
      lines.push(`**Area:** ${area.label}`)
      lines.push('')
      lines.push(`**Requirement:** ${item.requirement}`)
      lines.push('')
      lines.push(`**What the code shows:** ${item.explanation}`)
      if (item.evidence.length > 0)
        lines.push('', `**Evidence:** ${item.evidence.map(formatEvidence).join(', ')}`)
      lines.push('', '---', '')
    }
  }

  if (count === 0) lines.push('_No blockers, gaps, concerns, or open questions were found._')
  return tidy(lines)
}

export function formatEvidence(evidence: Evidence): string {
  return `\`${evidence.file}\` lines ${evidence.startLine}–${evidence.endLine}`
}

function areaSection(lines: string[], area: ExportArea, isSingleArea: boolean): void {
  const { analysis, meta, specComparison } = area
  const heading = isSingleArea ? '##' : '###'
  if (!isSingleArea) {
    lines.push(`## Area: ${area.label}`, '')
    lines.push(analysis.summary, '')
  }
  if (meta)
    lines.push(
      `_From \`${meta.selectionLabel}\` · ${meta.includedFiles} file(s) reviewed, ${meta.excludedFiles} excluded · Confidence: ${analysis.confidence}_`,
      '',
    )

  findingSection(lines, `${heading} What's working`, analysis.whatsWorking)
  findingSection(lines, `${heading} Must fix before launch`, analysis.perspectives.pm.mvpMustFix)
  findingSection(lines, `${heading} Missing states`, analysis.missingStates)
  findingSection(lines, `${heading} UX concerns`, analysis.uxConcerns)
  findingSection(lines, `${heading} Design system`, analysis.perspectives.designer.designSystem)
  findingSection(lines, `${heading} Needs a decision`, analysis.risks)
  findingSection(lines, `${heading} Open questions`, analysis.openQuestions)
  findingSection(lines, `${heading} Technical notes`, analysis.technicalNotes)

  if (analysis.states.length > 0) {
    lines.push(
      `${heading} UX states`,
      '',
      '| State | Status | Explanation |',
      '| --- | --- | --- |',
    )
    for (const state of analysis.states) lines.push(stateRow(state))
    lines.push('')
  }

  if (specComparison) {
    lines.push(`${heading} Spec comparison`, '', specComparison.summary, '')
    if (specComparison.items.length > 0) {
      lines.push('| Requirement | Status | Notes |', '| --- | --- | --- |')
      for (const item of specComparison.items)
        lines.push(
          `| ${escapeCell(item.requirement)} | ${gapStatusLabel(item.status)} | ${escapeCell(item.explanation)}${evidenceSuffix(item.evidence)} |`,
        )
      lines.push('')
    }
  }
}

function nextStepsSection(lines: string[], heading: string, steps: NextStep[]): void {
  if (steps.length === 0) return
  lines.push(heading, '')
  steps.forEach((step, index) => {
    const qualifier = step.required
      ? 'Required before the analysis can be considered complete'
      : `${capitalize(step.userImpact)} user impact · ${capitalize(step.effort)} effort`
    lines.push(`${index + 1}. **${step.title}** — ${qualifier}`)
    if (step.detail) lines.push(`   ${step.detail}${evidenceSuffix(step.evidence)}`)
  })
  lines.push('')
}

function labeledFindingSection(
  lines: string[],
  heading: string,
  groups: { label: string; findings: Finding[] }[],
  showLabels: boolean,
): void {
  const rows = groups.flatMap(({ label, findings }) =>
    findings.map(
      (finding) =>
        `- ${showLabels ? `**${label}:** ` : ''}${finding.text} _(${finding.confidence})_${evidenceSuffix(finding.evidence)}`,
    ),
  )
  if (rows.length === 0) return
  lines.push(heading, '', ...rows, '')
}

function findingSection(lines: string[], heading: string, findings: Finding[]): void {
  labeledFindingSection(lines, heading, [{ label: '', findings }], false)
}

function section(lines: string[], title: string, body: string): void {
  if (!body.trim()) return
  lines.push(`## ${title}`, '', body.trim(), '')
}

function ticketBlock({
  count,
  source,
  finding,
  area,
}: {
  count: number
  source: TicketSource
  finding: Finding
  area: ExportArea
}): string[] {
  const lines: string[] = []
  lines.push(`## Ticket ${count}: ${source.titlePrefix} — ${truncate(finding.text, 80)}`)
  lines.push('')
  lines.push(`**Type:** ${source.category}`)
  lines.push(`**Area:** ${area.label}`)
  lines.push(`**Confidence:** ${finding.confidence}`)
  lines.push('')
  lines.push(`**Description:** ${finding.text}`)
  if (finding.evidence.length > 0)
    lines.push('', `**Evidence:** ${finding.evidence.map(formatEvidence).join(', ')}`)
  lines.push('', '---', '')
  return lines
}

function gapTicketLabel(status: 'partial' | 'missing' | 'not-specified'): string {
  if (status === 'missing') return 'Implement specified requirement'
  if (status === 'partial') return 'Complete partially built requirement'
  return 'Review unspecified behavior'
}

function gapStatusLabel(status: 'built' | 'partial' | 'missing' | 'not-specified'): string {
  const labels = {
    built: '✅ Built',
    partial: '🟡 Partial',
    missing: '❌ Missing',
    'not-specified': '➕ Not in spec',
  } as const
  return labels[status]
}

function areaNames(areas: ExportArea[]): string {
  return areas.map((area) => area.label).join(', ')
}

function areaCountLabel(areas: ExportArea[]): string {
  const files = areas.reduce((total, area) => total + (area.meta?.includedFiles ?? 0), 0)
  const areaPart = areas.length === 1 ? '1 area' : `${areas.length} areas`
  return `${areaPart} · ${files} file(s) reviewed`
}

function stateRow(state: UxState): string {
  return `| ${escapeCell(state.name)} | ${capitalize(state.status)} | ${escapeCell(state.description)} |`
}

function evidenceSuffix(evidence: Evidence[]): string {
  if (evidence.length === 0) return ''
  return ` — ${evidence.map(formatEvidence).join(', ')}`
}

function capitalize(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1)
}

function truncate(value: string, max: number): string {
  return value.length <= max ? value : `${value.slice(0, max - 1)}…`
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

function tidy(lines: string[]): string {
  return (
    lines
      .join('\n')
      .replace(/\n{3,}/g, '\n\n')
      .trimEnd() + '\n'
  )
}

interface TicketSource {
  category: string
  findings: Finding[]
  titlePrefix: string
}
