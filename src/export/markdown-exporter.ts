import type { ProductAnalysis, Evidence, Finding, UxState, GapAnalysis } from '../analysis/schemas'
import type { AnalysisMeta } from '../analysis/types'

export function exportToMarkdown(
  analysis: ProductAnalysis,
  meta?: AnalysisMeta,
  specComparison?: GapAnalysis,
): string {
  const lines: string[] = []
  lines.push(`# ${analysis.featureName}`)
  lines.push('')
  if (meta)
    lines.push(
      `> Generated by Gizmo from \`${meta.selectionLabel}\` · ${meta.includedFiles} file(s) reviewed, ${meta.excludedFiles} excluded · Confidence: ${analysis.confidence}`,
      '',
    )

  lines.push(
    `**Status:** ${statusLabel(analysis.completionStatus)} · **Risk:** ${capitalize(analysis.riskLevel)} · **Confidence:** ${capitalize(analysis.confidence)}`,
    '',
  )

  section(
    lines,
    'Summary',
    [analysis.summary, analysis.evidenceSummary].filter(Boolean).join('\n\n'),
  )

  findingSection(lines, "What's working", analysis.whatsWorking)

  if (analysis.nextSteps.length > 0) {
    lines.push('## Recommended next steps', '')
    analysis.nextSteps.forEach((step, index) => {
      const qualifier = step.required
        ? 'Required before the analysis can be considered complete'
        : `${capitalize(step.userImpact)} user impact · ${capitalize(step.effort)} effort`
      lines.push(`${index + 1}. **${step.title}** — ${qualifier}`)
      if (step.detail) lines.push(`   ${step.detail}${evidenceSuffix(step.evidence)}`)
    })
    lines.push('')
  }

  section(lines, 'User goal', analysis.userGoal)

  if (analysis.primaryActions.length > 0) {
    lines.push('## Main actions', '')
    for (const action of analysis.primaryActions)
      lines.push(`- **${action.label}** — ${action.behavior}${evidenceSuffix(action.evidence)}`)
    lines.push('')
  }

  if (analysis.userFlow.length > 0) {
    lines.push('## User flow', '')
    for (const step of analysis.userFlow)
      lines.push(`${step.step}. **${step.title}** — ${step.description} _(${step.confidence})_`)
    lines.push('')
  }

  if (analysis.states.length > 0) {
    lines.push('## UX states', '', '| State | Status | Explanation |', '| --- | --- | --- |')
    for (const state of analysis.states) lines.push(stateRow(state))
    lines.push('')
  }

  if (specComparison) {
    lines.push('## Spec comparison', '', specComparison.summary, '')
    if (specComparison.items.length > 0) {
      lines.push('| Requirement | Status | Notes |', '| --- | --- | --- |')
      for (const item of specComparison.items)
        lines.push(
          `| ${escapeCell(item.requirement)} | ${gapStatusLabel(item.status)} | ${escapeCell(item.explanation)}${item.evidence.length > 0 ? ' — ' + item.evidence.map(formatEvidence).join(', ') : ''} |`,
        )
      lines.push('')
    }
  }

  const { designer, pm, stakeholder } = analysis.perspectives
  findingSection(lines, 'Pain points (Designer)', designer.painPoints)
  findingSection(lines, 'Design system & visual consistency (Designer)', designer.designSystem)
  if (pm.valueProposition) section(lines, 'Positioning (PM)', pm.valueProposition)
  findingSection(lines, 'Selling points (PM)', pm.sellingPoints)
  findingSection(lines, 'MVP: must fix before selling (PM)', pm.mvpMustFix)
  findingSection(lines, 'Analytics & measurement (PM)', pm.analytics)
  if (stakeholder.launchSummary || stakeholder.launchGoal)
    section(
      lines,
      'Launch overview (Stakeholder)',
      [
        stakeholder.launchSummary,
        stakeholder.launchGoal ? `**Goal of this launch:** ${stakeholder.launchGoal}` : '',
      ]
        .filter(Boolean)
        .join('\n\n'),
    )
  findingSection(lines, "What's blocking release (Stakeholder)", stakeholder.launchBlockers)

  findingSection(lines, 'Business rules', analysis.businessRules)
  findingSection(lines, 'Permissions', analysis.permissions)
  findingSection(lines, 'Dependencies', [
    ...analysis.dataDependencies,
    ...analysis.externalServices,
  ])
  findingSection(lines, 'UX concerns', analysis.uxConcerns)
  findingSection(lines, 'Missing states', analysis.missingStates)
  findingSection(lines, 'Risks', analysis.risks)
  findingSection(lines, 'Acceptance criteria', analysis.acceptanceCriteria)
  findingSection(lines, 'Open questions', analysis.openQuestions)

  const allEvidence = collectEvidence(analysis)
  if (allEvidence.length > 0) {
    lines.push('## Evidence', '')
    for (const evidence of allEvidence) lines.push(`- ${formatEvidence(evidence)}`)
    lines.push('')
  }

  return (
    lines
      .join('\n')
      .replace(/\n{3,}/g, '\n\n')
      .trimEnd() + '\n'
  )
}

interface TicketSource {
  category: string
  findings: Finding[]
  titlePrefix: string
}

export function exportTicketsToMarkdown(
  analysis: ProductAnalysis,
  meta?: AnalysisMeta,
  specComparison?: GapAnalysis,
): string {
  const lines: string[] = []
  lines.push(`# ${analysis.featureName} — suggested tickets`)
  lines.push('')
  lines.push(
    `> Generated by Gizmo${meta ? ` from \`${meta.selectionLabel}\`` : ''}. Each block below is ready to paste into Jira, Linear, or any tracker. Review before filing — "Likely" and "Unclear" findings should be verified first.`,
  )
  lines.push('')

  const sources: TicketSource[] = [
    { category: 'Gap', findings: analysis.missingStates, titlePrefix: 'Add missing state' },
    { category: 'Risk', findings: analysis.risks, titlePrefix: 'Mitigate risk' },
    { category: 'UX', findings: analysis.uxConcerns, titlePrefix: 'Fix UX concern' },
    { category: 'Question', findings: analysis.openQuestions, titlePrefix: 'Clarify' },
  ]

  let count = 0
  for (const source of sources) {
    for (const finding of source.findings) {
      count += 1
      lines.push(...ticketBlock(count, source, finding, analysis))
    }
  }

  if (specComparison) {
    for (const item of specComparison.items) {
      if (item.status === 'built') continue
      count += 1
      const label =
        item.status === 'missing'
          ? 'Implement specified requirement'
          : item.status === 'partial'
            ? 'Complete partially built requirement'
            : 'Review unspecified behavior'
      lines.push(`## Ticket ${count}: ${label} — ${truncate(item.requirement, 80)}`)
      lines.push('')
      lines.push(`**Type:** Spec gap (${gapStatusLabel(item.status)})`)
      lines.push(`**Feature:** ${analysis.featureName}`)
      lines.push('')
      lines.push(`**Requirement:** ${item.requirement}`)
      lines.push('')
      lines.push(`**What the code shows:** ${item.explanation}`)
      if (item.evidence.length > 0)
        lines.push('', `**Evidence:** ${item.evidence.map(formatEvidence).join(', ')}`)
      lines.push('', '---', '')
    }
  }

  if (count === 0)
    lines.push('_No gaps, risks, concerns, or open questions were found in this analysis._')

  return (
    lines
      .join('\n')
      .replace(/\n{3,}/g, '\n\n')
      .trimEnd() + '\n'
  )
}

function ticketBlock(
  count: number,
  source: TicketSource,
  finding: Finding,
  analysis: ProductAnalysis,
): string[] {
  const lines: string[] = []
  lines.push(`## Ticket ${count}: ${source.titlePrefix} — ${truncate(finding.text, 80)}`)
  lines.push('')
  lines.push(`**Type:** ${source.category}`)
  lines.push(`**Feature:** ${analysis.featureName}`)
  lines.push(`**Confidence:** ${finding.confidence}`)
  lines.push('')
  lines.push(`**Description:** ${finding.text}`)
  if (finding.evidence.length > 0)
    lines.push('', `**Evidence:** ${finding.evidence.map(formatEvidence).join(', ')}`)
  lines.push('', '---', '')
  return lines
}

function gapStatusLabel(status: 'built' | 'partial' | 'missing' | 'not-specified'): string {
  const labels = {
    built: '✅ Built',
    partial: '🟡 Partial',
    missing: '❌ Missing',
    'not-specified': '➕ Not in spec',
  } as const
  return labels[status]
}

function capitalize(value: string): string {
  return value.charAt(0).toUpperCase() + value.slice(1)
}

function statusLabel(
  status: 'complete' | 'mostly-complete' | 'in-progress' | 'not-started',
): string {
  const labels = {
    complete: 'Complete',
    'mostly-complete': 'Mostly complete',
    'in-progress': 'In progress',
    'not-started': 'Not started',
  } as const
  return labels[status]
}

function truncate(value: string, max: number): string {
  return value.length <= max ? value : `${value.slice(0, max - 1)}…`
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

function section(lines: string[], title: string, body: string): void {
  if (!body.trim()) return
  lines.push(`## ${title}`, '', body.trim(), '')
}

function findingSection(lines: string[], title: string, findings: Finding[]): void {
  if (findings.length === 0) return
  lines.push(`## ${title}`, '')
  for (const finding of findings)
    lines.push(`- ${finding.text} _(${finding.confidence})_${evidenceSuffix(finding.evidence)}`)
  lines.push('')
}

function stateRow(state: UxState): string {
  const status = state.status.charAt(0).toUpperCase() + state.status.slice(1)
  return `| ${escapeCell(state.name)} | ${status} | ${escapeCell(state.description)} |`
}

function evidenceSuffix(evidence: Evidence[]): string {
  if (evidence.length === 0) return ''
  return ` — ${evidence.map(formatEvidence).join(', ')}`
}

export function formatEvidence(evidence: Evidence): string {
  return `\`${evidence.file}\` lines ${evidence.startLine}–${evidence.endLine}`
}

function collectEvidence(analysis: ProductAnalysis): Evidence[] {
  const all: Evidence[] = [
    ...analysis.primaryActions.flatMap((action) => action.evidence),
    ...analysis.states.flatMap((state) => state.evidence),
    ...[
      ...analysis.businessRules,
      ...analysis.permissions,
      ...analysis.dataDependencies,
      ...analysis.externalServices,
      ...analysis.components,
      ...analysis.risks,
      ...analysis.uxConcerns,
      ...analysis.missingStates,
      ...analysis.openQuestions,
      ...analysis.acceptanceCriteria,
      ...analysis.changeImpact,
      ...analysis.technicalNotes,
    ].flatMap((finding) => finding.evidence),
  ]
  const seen = new Set<string>()
  return all.filter((evidence) => {
    const key = `${evidence.file}:${evidence.startLine}:${evidence.endLine}`
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })
}
